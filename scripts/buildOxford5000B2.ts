// Parser helper
export interface ParsedEntry {
  sourceOrder: number;
  sourceEntry: string;
  headword: string;
  qualifier?: string;
  partOfSpeech: string;
  cefr: "B2";
  sourceCollection: "oxford5000-extra";
  id: string;
}

export function parseSourceLine(line: string): ParsedEntry {
  const match = line.match(/^(\d{4})\.\s+(.+)$/);
  if (!match) {
    throw new Error(`Invalid line format: ${line}`);
  }
  const sourceOrder = parseInt(match[1], 10);
  const entryStr = match[2].trim();

  // Check for qualifier in parentheses: e.g. "counter (long flat surface) n."
  let headword = '';
  let qualifier: string | undefined = undefined;
  let partOfSpeech = '';

  const qualMatch = entryStr.match(/^([a-zA-Z\s-]+)\s+\((.+?)\)\s+(.+)$/);
  if (qualMatch) {
    headword = qualMatch[1].trim();
    qualifier = qualMatch[2].trim();
    partOfSpeech = qualMatch[3].trim();
  } else {
    // Standard format: "absorb v." or "part-time adj./adv." or "trillion number"
    const lastSpaceIdx = entryStr.lastIndexOf(' ');
    if (lastSpaceIdx === -1) {
      throw new Error(`Cannot split headword and POS: ${entryStr}`);
    }
    headword = entryStr.substring(0, lastSpaceIdx).trim();
    partOfSpeech = entryStr.substring(lastSpaceIdx + 1).trim();
  }

  // Stable ID generator
  const slugHeadword = headword.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  const slugPos = partOfSpeech.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
  const slugQual = qualifier ? `-${qualifier.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')}` : '';

  const id = `ox5000-extra-b2-${slugHeadword}${slugQual}-${slugPos}`;

  return {
    sourceOrder,
    sourceEntry: entryStr,
    headword,
    qualifier,
    partOfSpeech,
    cefr: "B2",
    sourceCollection: "oxford5000-extra",
    id
  };
}
