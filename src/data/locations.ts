/**
 * Filter Turkish cities with case-insensitive and Turkish character support
 */
export function filterTurkishCities(query: string): string[] {
  if (!query || !query.trim()) return TURKISH_CITIES;
  const q = query.trim().toLocaleLowerCase('tr-TR');
  return TURKISH_CITIES.filter((city) =>
    city.toLocaleLowerCase('tr-TR').includes(q)
  );
}
